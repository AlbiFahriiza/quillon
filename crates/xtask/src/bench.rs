//! `cargo xtask bench` — the published benchmark harness (research/Q).
//!
//! Honesty rules baked in: a corpus (never a single synthetic scene),
//! median + p10/p90 over N runs, render-only (encoder excluded) next
//! to end-to-end, reproducibility re-checked by frame hash, and the
//! hardware/threads/encoder context printed with the numbers. The
//! results table in `docs/benchmarks.md` is written by this code —
//! never typed by hand.

use anyhow::{Context, Result, bail};
use quillon_core::frame_source::NullFrameSource;
use quillon_core::time::frame_tick;
use quillon_core::validate_str;
use quillon_render::Renderer;
use sha2::{Digest, Sha256};
use std::path::PathBuf;
use std::process::Command;
use std::time::Instant;

const RUNS: usize = 5;

struct Doc {
    name: String,
    path: PathBuf,
}

struct Stats {
    median: f64,
    p10: f64,
    p90: f64,
}

/// median/p10/p90 of a sample (ms), sorted-index method.
fn stats(samples: &mut [f64]) -> Stats {
    samples.sort_by(|a, b| a.total_cmp(b));
    let at = |q: f64| -> f64 {
        let idx = ((samples.len() - 1) as f64 * q).round() as usize;
        samples[idx.min(samples.len() - 1)]
    };
    Stats {
        median: at(0.5),
        p10: at(0.1),
        p90: at(0.9),
    }
}

pub fn run() -> Result<()> {
    let root = crate::repo_root();
    let mut docs: Vec<Doc> = std::fs::read_dir(root.join("templates"))?
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|ext| ext == "json"))
        .map(|path| Doc {
            name: path.file_stem().unwrap().to_string_lossy().into_owned(),
            path,
        })
        .collect();
    // The acceptance fixture joins the corpus (small, batch-shaped).
    docs.push(Doc {
        name: "mini-batch".into(),
        path: root.join("crates/quillon-cli/tests/fixtures/template-mini.json"),
    });
    docs.sort_by(|a, b| a.name.cmp(&b.name));
    if docs.is_empty() {
        bail!("no corpus documents found");
    }

    // The e2e leg uses the release binary; build it first (incremental).
    let status = Command::new("cargo")
        .args([
            "build",
            "--release",
            "-p",
            "quillon-cli",
            "--bin",
            "quillon",
        ])
        .status()
        .context("spawn cargo build")?;
    if !status.success() {
        bail!("release build failed");
    }
    let bin = root.join("target/release/quillon");
    let out_dir = std::env::temp_dir().join("quillon-bench");
    std::fs::create_dir_all(&out_dir)?;

    let cpu = std::fs::read_to_string("/proc/cpuinfo")
        .ok()
        .and_then(|t| {
            t.lines()
                .find(|l| l.starts_with("model name"))
                .map(|l| l.split(':').nth(1).unwrap_or("").trim().to_string())
        })
        .unwrap_or_else(|| "unknown".into());
    let cores = std::thread::available_parallelism()
        .map(|n| n.get())
        .unwrap_or(0);
    let ffmpeg = Command::new("ffmpeg")
        .arg("-version")
        .output()
        .ok()
        .map(|o| {
            String::from_utf8_lossy(&o.stdout)
                .lines()
                .next()
                .unwrap_or("?")
                .to_string()
        })
        .unwrap_or_else(|| "not found".into());

    let mut md = String::new();
    md.push_str("# Benchmarks\n\n");
    md.push_str(&format!(
        "Generated by `cargo xtask bench` — do not edit by hand; rerun the\n\
         harness to refresh. Method: {RUNS} runs per document, median with\n\
         p10/p90; render-only frames exclude the encoder (PNG-path raster,\n\
         same `Renderer` as the real render); end-to-end is document to MP4\n\
         on disk via the release binary, software encode (libx264), no\n\
         frame cache. Reproducibility: all frame hashes identical across\n\
         the runs.\n\n"
    ));
    md.push_str(&format!(
        "Context: {cpu}; {cores} logical cores; {ffmpeg}.\n\n"
    ));
    md.push_str("| document | validate (med) | validate p10/p90 | render-only fps (med) | fps p10/p90 | e2e (med) | e2e p10/p90 | reproducible |\n");
    md.push_str("|---|---|---|---|---|---|---|---|\n");

    for doc in &docs {
        let base = doc.path.parent().unwrap().to_path_buf();
        let text = std::fs::read_to_string(&doc.path)?;
        let validated = || -> Result<quillon_core::Document> {
            validate_str(&text, &base)
                .map_err(|errors| anyhow::anyhow!("{} is invalid: {errors:?}", doc.path.display()))
        };
        let frames = validated()?.frame_count() as usize;

        // (a) validate cost.
        let mut val_ms = Vec::with_capacity(RUNS);
        for _ in 0..RUNS {
            let t = Instant::now();
            validated()?;
            val_ms.push(t.elapsed().as_secs_f64() * 1000.0);
        }

        // (b) render-only frames/sec + (d) reproducibility.
        let document = validated()?;
        let renderer = Renderer::new(&document, &base)?;
        let mut fps_runs = Vec::with_capacity(RUNS);
        let mut first_hashes: Option<Vec<String>> = None;
        let mut reproducible = true;
        for _ in 0..RUNS {
            let t = Instant::now();
            let mut hashes = Vec::with_capacity(frames);
            for i in 0..document.frame_count() {
                let tick = (i as i64) * frame_tick(document.fps);
                let frame = renderer.render_tick(tick, &NullFrameSource)?;
                hashes.push(hex(&Sha256::digest(&frame.rgba)));
            }
            let elapsed = t.elapsed().as_secs_f64();
            fps_runs.push(frames as f64 / elapsed);
            match &first_hashes {
                None => first_hashes = Some(hashes),
                Some(seen) => {
                    if seen != &hashes {
                        reproducible = false;
                    }
                }
            }
        }

        // (c) end-to-end through the release binary.
        let out = out_dir.join(format!("{}.mp4", doc.name));
        let mut e2e_ms = Vec::with_capacity(RUNS);
        for _ in 0..RUNS {
            let t = Instant::now();
            let output = Command::new(&bin)
                .arg("render")
                .arg(&doc.path)
                .arg("-o")
                .arg(&out)
                .output()
                .context("spawn quillon render")?;
            if !output.status.success() {
                bail!(
                    "render failed for {}: {}",
                    doc.path.display(),
                    String::from_utf8_lossy(&output.stderr)
                );
            }
            e2e_ms.push(t.elapsed().as_secs_f64() * 1000.0);
        }

        let v = stats(&mut val_ms);
        let f = stats(&mut fps_runs);
        let e = stats(&mut e2e_ms);
        let val_cell = format!("{:.1}", v.median);
        let val_spread = format!("{:.1} / {:.1}", v.p10, v.p90);
        let fps_cell = format!("{:.0}", f.median);
        let fps_spread = format!("{:.0} / {:.0}", f.p10, f.p90);
        let e2e_cell = format!("{:.0}", e.median);
        let e2e_spread = format!("{:.0} / {:.0}", e.p10, e.p90);
        let repro_cell = if reproducible { "yes" } else { "NO" };
        md.push_str(&format!(
            "| {} | {val_cell} | {val_spread} | {fps_cell} | {fps_spread} | {e2e_cell} | {e2e_spread} | {repro_cell} |\n",
            doc.name,
        ));
        println!(
            "{}: {} frames, validate {:.1}ms, {:.0} fps render-only, {:.0}ms e2e, reproducible={}",
            doc.name, frames, v.median, f.median, e.median, reproducible
        );
    }

    md.push_str("\n## Reading the numbers\n\n");
    md.push_str("- Render-only fps measures the compositor (tiny-skia raster,\n");
    md.push_str("  linear-light blend, text shaping); it is the number comparable\n");
    md.push_str("  across machines and against other engines' render-only claims.\n");
    md.push_str("- End-to-end includes decode, composite, x264 encode, and mux via\n");
    md.push_str("  the system ffmpeg — expect it to dominate on all CPU paths.\n");
    md.push_str("- Validate cost is the agent-loop step: document in, verdict out.\n");
    md.push_str("- The corpus is the template gallery plus the batch acceptance\n");
    md.push_str("  fixture; no single synthetic scene headlines anything.\n");

    let out_path = root.join("docs/benchmarks.md");
    std::fs::write(&out_path, md).with_context(|| format!("write {}", out_path.display()))?;
    println!("\nwrote {}", out_path.display());
    Ok(())
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}
